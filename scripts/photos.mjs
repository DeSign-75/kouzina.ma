// Scans public/photos and writes:
//   src/data/photos.ts        slug -> image url
//   src/data/photoCredits.ts  slug -> source + licence (from scripts/photo-credits.json)
//
// Run after adding, replacing or removing dish photography: npm run photos
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, parse } from "node:path";

const ROOT = process.cwd();
const DIR = join(ROOT, "public", "photos");
const CREDITS_JSON = join(ROOT, "scripts", "photo-credits.json");
const ALLOWED = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

const found = new Map();

let files = [];
try {
  files = readdirSync(DIR);
} catch {
  console.warn(`No photo folder yet at ${DIR}`);
}

for (const file of files) {
  const { name, ext } = parse(file);
  const lower = ext.toLowerCase();
  if (!ALLOWED.has(lower)) continue;
  // Prefer the richest format if several exist for the same slug.
  const rank = [".avif", ".webp", ".jpg", ".jpeg", ".png"].indexOf(lower);
  const current = found.get(name);
  if (current && current.rank <= rank) continue;
  found.set(name, { ext: lower, rank });
}

const slugs = [...found.keys()].sort((a, b) => a.localeCompare(b));

const photoEntries = slugs
  .map((slug) => {
    const { ext } = found.get(slug);
    return `  ${JSON.stringify(slug)}: "/photos/${slug}${ext}",`;
  })
  .join("\n");

writeFileSync(
  join(ROOT, "src", "data", "photos.ts"),
  `// Generated by \`npm run photos\` — do not edit by hand.
// Maps a recipe slug to its food photograph in /public/photos.
// Any recipe missing here falls back to its hand-drawn illustration.

export const PHOTOS: Record<string, string> = {
${photoEntries}
};
`,
  "utf8"
);

/* ---------- credits ---------- */

let credits = {};
try {
  credits = JSON.parse(readFileSync(CREDITS_JSON, "utf8"));
} catch {
  credits = {};
}

const kept = slugs.filter((slug) => credits[slug]);
const creditEntries = kept
  .map((slug) => {
    const c = credits[slug];
    const field = (value) => JSON.stringify(value ?? "");
    return `  ${JSON.stringify(slug)}: { title: ${field(c.title)}, author: ${field(
      c.author
    )}, license: ${field(c.license)}, licenseUrl: ${field(c.licenseUrl)}, page: ${field(
      c.page
    )} },`;
  })
  .join("\n");

writeFileSync(
  join(ROOT, "src", "data", "photoCredits.ts"),
  `// Generated by \`npm run photos\` — source and licence for each dish photo.
export interface PhotoCredit {
  title: string;
  author: string;
  license: string;
  licenseUrl: string;
  page: string;
}

export const PHOTO_CREDITS: Record<string, PhotoCredit> = {
${creditEntries}
};
`,
  "utf8"
);

console.log(
  `photos: ${slugs.length} linked (${kept.length} with credits) -> src/data/photos.ts`
);
